"""
Deco BE85 (FW 1.3.0) が受け付ける luci form と TMP opcode の一覧。

どちらもファームウェアのイメージから復元した。luci は controller の dispatch table が持つ
`form` と `operation` の組、TMP は `tmpsvr` が持つ opcode と controller・form・operation の
対応のうち、Deco アプリ向けの範囲 (0x4000-0x7FFF) で、controller の dispatch table に実在するもの。
同じ組に複数の opcode があるときは最小の番号を使う。どの opcode も同じ controller の処理を呼び、
ほかのノードへ転送するかどうかだけを、ルーターが実行時の設定で opcode ごとに決める。

次のものは含めない。
- luci: ログイン前に使う module (`login` など) と、mesh のノード間の処理。
- luci: multipart やファイルの送受信を前提とし、JSON の envelope では呼べない form
  (`admin/firmware` の設定のバックアップ・復元、ファームウェアの upload など)。
- luci: 管理パスワード・cloud の token など、資格情報を返す read。
- TMP: 初期設定・工場試験 (0x8000-) と mesh のノード間 (0xC000-) の opcode、debug・試験用の opcode。
- TMP: ルーターからの通知と同じ opcode (0x4015) を使う操作。同じ txid の通知と応答を区別できない
  (同じ操作は luci の `admin/client?form=traffic_stat` の `client` で呼べる)。
"""

from typing import NamedTuple


class LuciOperation(NamedTuple):
    """luci の Web API (`/cgi-bin/luci/;stok=<stok>/<module>?form=<form>`) の 1 操作。"""

    module: str
    form: str
    operation: str
    # Deco 自体やネットワーク全体に届かなくなる操作 (再起動・初期化・ファームウェアの更新・
    # WAN の切断・LAN・WAN・mesh・IPTV の接続設定やポートの媒体・動作モード・メインノード・
    # mesh グループの変更) と、元に戻せない操作 (ノードや cloud の紐付けの変更・資格情報の変更・
    # ログ・履歴・レポート・メッセージの消去)。Wi-Fi や VPN など、この API から設定し直せる
    # 個別の設定の変更は含めない。
    destructive: bool = False

    @property
    def path(self) -> str:
        return f"{self.module}?form={self.form}"


class TmpOperation(NamedTuple):
    """
    Deco アプリが TMP で呼ぶ 1 操作。

    controller は `luci.controller.admin.mobile_app.<controller>` の名前 (`wifidog` だけは
    `luci.controller.admin.wifidog`)。
    """

    opcode: int
    controller: str
    form: str
    operation: str
    # LuciOperation.destructive と同じ。
    destructive: bool = False


